/** Biểu tượng theo tên; tên lạ hoặc để trống thì dùng `fallback`. */
export function iconByName(name: string | null | undefined, fallback: LucideIcon): LucideIcon {
  return (name && ICONS[name]) || fallback
}

/** true nếu tên có trong danh sách (để admin biết trước khi lưu). */
export function isKnownIcon(name: string | null | undefined): boolean {
  return !!name && name in ICONS
}
